// конкретного сообщения не вызывается вообще. Значит, если текст всё же
// дошёл до LLM (askLLM) — точный триггер не совпал. Из-за этого в описании
// каждой фичи ниже — не "плавное" описание, а КОНКРЕТНЫЙ формат фразы,
// который реально сработает, чтобы модель могла честно подсказать его
// пользователю, а не описывать функцию расплывчато.
//
// Если меняешь логику триггеров в index.js (regex погоды/фильмов/музыки и
// т.п.) — не забудь актуализировать соответствующий блок ниже, иначе бот
// начнёт советовать людям фразы, которые на самом деле не сработают.

