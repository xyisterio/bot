export function cardImageFileName(card) {
  if (card.arcana === "major") {
    return `major-${String(card.id).padStart(2, "0")}.jpg`;
  }
  return `${card.id}.jpg`; // например "wands-1.jpg", "cups-queen.jpg"
}

// ==== Тасование и расклады ====

function shuffledIndices(length) {
  const idx = Array.from({ length }, (_, i) => i);
  for (let i = idx.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [idx[i], idx[j]] = [idx[j], idx[i]];
  }
  return idx;
}

// Тянет n уникальных карт из полной колоды, для каждой независимо (50/50)
// решает, перевёрнута она или нет. Возвращает [{ card, reversed }, ...].
export function drawCards(n, { allowReversed = true } = {}) {
  const order = shuffledIndices(DECK.length).slice(0, n);
  return order.map((i) => ({
    card: DECK[i],
    reversed: allowReversed ? Math.random() < 0.5 : false,
  }));
}

// "Карта дня" — намеренно ДЕТЕРМИНИРОВАНА по (userId, дата), а не чисто
// случайна: та же идея, что у daily-card в готовых taro-библиотеках —
// если человек за день спросит карту дня дважды, должна выпасть та же
// самая карта, а не разная при каждом обращении. tz нужен, чтобы "день"
// считался по локальному времени человека, а не по UTC сервера (та же
// логика часового пояса, что уже используется в natal.js для транзитов).
function dailySeed(userId, tz) {
  const dateStr = new Date().toLocaleDateString("en-CA", { timeZone: tz || "UTC" }); // YYYY-MM-DD
  const raw = `${userId}:${dateStr}`;
  let hash = 0;
  for (let i = 0; i < raw.length; i++) {
    hash = (hash * 31 + raw.charCodeAt(i)) >>> 0;
  }
  return hash;
}

export function drawDailyCard(userId, tz) {
  const seed = dailySeed(userId, tz);
  const card = DECK[seed % DECK.length];
  const reversed = ((seed >>> 8) % 2) === 1;
  return { card, reversed };
}

