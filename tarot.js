// ==== Форматирование расклада в контекст для LLM ====
//
// spreadType — ключ из SPREADS. drawn — результат drawCards(SPREADS[spreadType].count).
// question — свободный текст вопроса человека, если он его задал (может
// быть null — например, "карта дня" обычно без вопроса).
export function buildTarotContext(spreadType, drawn, question) {
  const spread = SPREADS[spreadType];
  const lines = [];
  if (question) {
    lines.push(`Вопрос человека: "${question}"`);
  }
  lines.push("Расклад Таро (карты вытянуты случайно, значения ниже — реальные, фиксированные, не выдумывай других):");
  drawn.forEach(({ card, reversed }, i) => {
    const posLabel = spread.positions[i] || `Карта ${i + 1}`;
    const orientation = reversed ? "перевёрнутая" : "прямая";
    const meaning = reversed ? card.revRu : card.upRu;
    lines.push(`\n${posLabel}: «${card.nameRu}» (${orientation})\nЗначение: ${meaning}`);
  });
  return lines.join("\n");
}

// ==== Распознавание запроса в обычном тексте ====
//
// Та же anchored-к-началу-сообщения философия, что у NOT_CYRILLIC_LETTER /
// horoscopeRe в natal.js — предсказуемая фраза, которую можно честно
// подсказать в skills.js, а не гадательный fuzzy-match.
const NOT_CYRILLIC_LETTER = "(?![а-яёА-ЯЁ])";

// ВАЖНО: как и в natal.js, \b тут не сработал бы после кириллицы (\b в JS
// основан на \w == [A-Za-z0-9_], кириллица туда не входит) — поэтому
// граница слова на каждой альтернативе задаётся через NOT_CYRILLIC_LETTER
// (negative lookahead на кириллическую букву сразу после триггера), а не
// через \b.
const TAROT_TRIGGER_RE = new RegExp(
  `^(?:карта\\s+дня${NOT_CYRILLIC_LETTER}|таро\\s+дня${NOT_CYRILLIC_LETTER}|` +
    `кельтский\\s+крест${NOT_CYRILLIC_LETTER}|расклад\\s+таро${NOT_CYRILLIC_LETTER}|` +
    `таро\\s+расклад${NOT_CYRILLIC_LETTER}|три\\s+карты${NOT_CYRILLIC_LETTER}|` +
    `таро${NOT_CYRILLIC_LETTER})`,
  "i"
);

// Возвращает { spreadType, question } либо null, если сообщение не похоже
// на запрос Таро. question — всё, что осталось после триггерной фразы
// (например "таро на новую работу" -> question = "на новую работу") — это
// и есть тот самый свободный вопрос человека, который дальше в index.js
// просто передаётся внутрь buildTarotContext(...) и уходит в LLM как есть,
// без всякой предобработки.
export function parseTarotQueryIntent(text) {
  const t = (text || "").trim();
  const m = TAROT_TRIGGER_RE.exec(t);
  if (!m) return null;

  const rest = t.slice(m[0].length).trim();
  const head = m[0].toLowerCase();

  let spreadType;
  if (head.includes("карта дня") || head.includes("таро дня")) {
    spreadType = "day";
  } else if (head.includes("кельтский крест")) {
    spreadType = "celtic";
  } else if (head.includes("три карты")) {
    spreadType = "three";
  } else if (/да\s+или\s+нет|да\/нет/i.test(rest)) {
    spreadType = "yesno";
  } else if (rest) {
    // Есть конкретный вопрос ("таро на новую работу", "расклад таро про
    // отношения") — это уже не абстрактная "карта дня", а разбор ситуации,
    // так что по умолчанию берём situation (ситуация/действие/итог), она
    // лучше подходит под вопрос, чем нейтральное прошлое/настоящее/будущее.
    spreadType = "situation";
  } else {
    // Голое "таро" / "расклад таро" без вопроса — три карты как разумный
    // дефолт (карта дня — отдельная явная фраза).
    spreadType = "three";
  }

  return { spreadType, question: rest || null };
}

