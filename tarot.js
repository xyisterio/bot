function buildMinorArcana() {
  const cards = [];
  for (const suit of SUITS) {
    for (const rank of NUMBER_RANKS) {
      cards.push({
        id: `${suit.key}-${rank.n}`,
        nameRu: `${rank.nameRu} ${suit.genitiveRu}`,
        nameEn: `${rank.n} of ${suit.nameRu}`,
        suit: suit.key,
        upRu: `${rank.up} — в сфере, за которую отвечает масть (${suit.theme})`,
        revRu: `${rank.rev} — там же, в сфере ${suit.theme}`,
      });
    }
    for (const court of COURT_RANKS) {
      cards.push({
        id: `${suit.key}-${court.key}`,
        nameRu: `${court.nameRu} ${suit.genitiveRu}`,
        nameEn: `${court.nameRu} of ${suit.nameRu}`,
        suit: suit.key,
        upRu: `${court.up} — в сфере ${suit.theme}`,
        revRu: `${court.rev} — в сфере ${suit.theme}`,
      });
    }
  }
  return cards;
}

